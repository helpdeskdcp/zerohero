// node web/build.mjs  -> ../../../../frontend/static/vendor/smartchart/
//   smartchart-vendor.js          the bundle (legal comments retained at end of file where upstream ships them)
//   THIRD_PARTY_LICENSES.txt      full licence text of EVERY npm package that esbuild actually bundled (derived from the metafile, not hand-listed)
//   THIRD_PARTY_NOTICES.md        provenance table: name, version, licence, npm integrity (from package-lock.json), bundle sha256
//   LICENSE-*.txt / NOTICE-vela.txt   the Apache-2.0 / AGPL-3.0 texts and Vela's NOTICE (attribution requirement)
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const out = resolve(pkgRoot, '..', '..', '..', 'frontend', 'static', 'vendor', 'smartchart');
mkdirSync(out, { recursive: true });
const bundlePath = join(out, 'smartchart-vendor.js');

const result = await build({
  entryPoints: [join(here, 'entry.js')],
  bundle: true, minify: true, format: 'iife', globalName: 'SmartChartVendor', platform: 'browser', target: ['es2020'],
  outfile: bundlePath, legalComments: 'eof', metafile: true, logLevel: 'info',
});

// ---- which packages are really inside the bundle (from esbuild's input list) ----------------------------------
const nm = join(pkgRoot, 'node_modules');
const bundled = new Map(); // name -> package dir
for (const input of Object.keys(result.metafile.inputs)) {
  const abs = resolve(pkgRoot, input);
  const i = abs.lastIndexOf(`${sep}node_modules${sep}`);
  if (i < 0) continue;
  const rest = abs.slice(i + `${sep}node_modules${sep}`.length).split(sep);
  const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0];
  bundled.set(name, abs.slice(0, i + `${sep}node_modules${sep}`.length) + name);
}

// Upstream ships prebuilt files (e.g. pinets' dist, the Vela-PineTS worker) that may inline their own declared dependencies, so those never show up
// as separate esbuild inputs. Include the closure of declared runtime `dependencies` too, labelled as such, so no notice is missed.
const inlined = new Map();
const queue = [...bundled.keys()];
while (queue.length) {
  const n = queue.pop();
  const dir = bundled.get(n) || inlined.get(n);
  const deps = Object.keys(JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).dependencies || {});
  for (const d of deps) {
    if (bundled.has(d) || inlined.has(d)) continue;
    const dd = join(nm, d);
    if (existsSync(join(dd, 'package.json'))) { inlined.set(d, dd); queue.push(d); }
  }
}

const lock = JSON.parse(readFileSync(join(pkgRoot, 'package-lock.json'), 'utf8')).packages || {};
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;
const rows = [];
let licenses = `Third-party licences for smartchart-vendor.js\n(generated by backend/app/smart_chart/web/build.mjs from the packages esbuild bundled; do not edit by hand)\n`;
for (const name of [...bundled.keys(), ...inlined.keys()].sort()) {
  const dir = bundled.get(name) || inlined.get(name);
  const viaDist = !bundled.has(name);
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const lic = typeof pj.license === 'string' ? pj.license : JSON.stringify(pj.license || pj.licenses || 'UNKNOWN');
  const entry = lock[`node_modules/${name}`] || {};
  const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
  rows.push({ name, version: pj.version, lic, integrity: entry.integrity || 'n/a', hasText: files.length > 0, viaDist });
  licenses += `\n${'='.repeat(78)}\n${name}@${pj.version}  —  ${lic}${viaDist ? '  [declared dependency of a bundled package; may be inlined in its prebuilt files]' : ''}\n${pj.repository ? `source: ${typeof pj.repository === 'string' ? pj.repository : pj.repository.url}\n` : ''}${'='.repeat(78)}\n`;
  if (files.length) for (const f of files) licenses += `\n--- ${f} ---\n${readFileSync(join(dir, f), 'utf8').trimEnd()}\n`;
  else licenses += `\n(this package ships no licence file; its package.json declares "${lic}". Copyright holder: ${pj.author ? (typeof pj.author === 'string' ? pj.author : pj.author.name) : 'see package source'})\n`;
}
writeFileSync(join(out, 'THIRD_PARTY_LICENSES.txt'), licenses);

copyFileSync(join(nm, '@luxalgo/vela', 'LICENSE'), join(out, 'LICENSE-vela-Apache-2.0.txt'));
copyFileSync(join(nm, '@luxalgo/vela', 'NOTICE'), join(out, 'NOTICE-vela.txt'));
copyFileSync(join(nm, '@luxalgo/vela-pinets', 'LICENSE'), join(out, 'LICENSE-vela-pinets-AGPL-3.0.txt'));
copyFileSync(join(nm, 'pinets', 'LICENSE'), join(out, 'LICENSE-pinets-AGPL-3.0.txt'));

const sha = createHash('sha256').update(readFileSync(bundlePath)).digest('hex');
const esb = JSON.parse(readFileSync(join(nm, 'esbuild', 'package.json'), 'utf8')).version;
const table = rows.map((r) => `| ${r.name}${r.viaDist ? ' (inlined by upstream dist)' : ''} | ${r.version} | ${r.lic} | \`${r.integrity}\` |`).join('\n');
writeFileSync(join(out, 'THIRD_PARTY_NOTICES.md'), `# Smart Chart vendor bundle

\`smartchart-vendor.js\` is built by \`backend/app/smart_chart/web/build.mjs\` (esbuild ${esb}, versions pinned in \`package.json\` / \`package-lock.json\`;
restore with \`npm ci\`, rebuild with \`npm run build:web\`). The package list below is generated: packages esbuild bundled as separate inputs, plus the declared runtime dependencies of those packages that upstream's prebuilt files may inline (marked "inlined by upstream dist").

- Bundle sha256: \`${sha}\`
- Full licence texts of every bundled package: \`THIRD_PARTY_LICENSES.txt\` (same directory)
- Apache-2.0 text and Vela's NOTICE: \`LICENSE-vela-Apache-2.0.txt\`, \`NOTICE-vela.txt\` — the Vela attribution mark stays visible on every Smart Chart page (built-in watermark left enabled, plus a text link in the page footer).
- AGPL-3.0 texts: \`LICENSE-pinets-AGPL-3.0.txt\`, \`LICENSE-vela-pinets-AGPL-3.0.txt\`

## Packages (${rows.length})

| Package | Version | Licence | npm integrity (package-lock.json) |
| --- | --- | --- | --- |
${table}

## Notes

- \`pinets\` and \`@luxalgo/vela-pinets\` are AGPL-3.0-only (PineTS is also offered by LuxAlgo under a commercial licence). Whether and how AGPL-3.0 §13 applies to this deployment has not been decided by the project owner; see \`backend/SMART_CHART.md\` ("Licensing").
- Upstream builds of some packages ship without licence headers, so the bundle cannot carry them inline; the texts and copyright lines are in \`THIRD_PARTY_LICENSES.txt\`. Legal comments that upstream does ship are retained at the end of the bundle.
- Pine Script and TradingView are trademarks of TradingView, Inc.; PineTS and Vela are independent LuxAlgo projects, not affiliated with or endorsed by TradingView.
`);
console.log(`vendor bundle -> ${out} (${bundled.size} bundled + ${inlined.size} declared-dependency packages, sha256 ${sha.slice(0, 12)}…)`);
